/* Writes the buyer FAQ accordion and the per-page structured data into the
 * hand-authored static pages.
 *
 * The static pages are authored HTML, not templates, so this writes into them
 * between marker comments and is safe to re-run: a second pass replaces what
 * the first pass wrote rather than appending a second copy. Run it after
 * editing src/data/faq.js:
 *
 *   npm run seo:pages
 *
 * It is deliberately not part of `npm run build` — a build that rewrites its
 * own source files leaves a dirty tree and makes a deploy hard to reason about.
 */

