/* --------------------------------------------------------------------------
   Rendering
   -------------------------------------------------------------------------- */

function faqSection(items, { label, accent }) {
  return `${FAQ_START}
      <section class="section-editorial faq-section" id="faq">
        <div class="site-container">
          <span class="section-label ${accent}">(${esc(label)})</span>
          <h2 class="editorial-heading">Questions buyers actually ask.</h2>
          <div class="faq-list">
${items
  .map(
    ({ q, a }) => `            <details class="faq-item">
              <summary>
                <span>${esc(q)}</span>
                <span class="faq-marker" aria-hidden="true"></span>
              </summary>
              <p class="faq-answer">${esc(a)}</p>
            </details>`
  )
  .join('\n')}
          </div>
        </div>
      </section>
      ${FAQ_END}`;
}

function ldBlock(nodes) {
  return `${LD_START}
    <script type="application/ld+json">
${JSON.stringify(graph(nodes), null, 2).replace(/</g, '\\u003c')}
    </script>
    ${LD_END}`;
}

/** Replaces a marked region, or inserts it before `anchor` the first time. */
function writeRegion(src, { start, end, body, anchor, indent }) {
  const open = src.indexOf(start);
  if (open !== -1) {
    const close = src.indexOf(end, open);
    if (close === -1) throw new Error(`unclosed region: ${start}`);
    return src.slice(0, open) + body + src.slice(close + end.length);
  }
  const at = src.indexOf(anchor);
  if (at === -1) throw new Error(`anchor not found: ${anchor}`);
  return src.slice(0, at) + body + '\n\n' + indent + src.slice(at);
}

function applyFaq(src, items, meta) {
  // Anchor on the CTA section's own comment where there is one, so a first
  // insertion does not strand that comment above the FAQ it no longer labels.
  const anchor = src.includes('<!-- CTA SECTION -->')
    ? '<!-- CTA SECTION -->'
    : '<section class="section-cta"';
  return writeRegion(src, {
    start: FAQ_START,
    end: FAQ_END,
    body: faqSection(items, meta),
    anchor,
    indent: '      ',
  });
}

function applyJsonLd(src, nodes) {
  return writeRegion(src, {
    start: LD_START,
    end: LD_END,
    body: ldBlock(nodes),
    anchor: '</head>',
    indent: '  ',
  });
}

/* --------------------------------------------------------------------------
   Homepage — keep the entity graph it already carries, drop its hand-written
   FAQPage node and emit one generated from the visible accordion instead, so
   the structured data and the page can no longer disagree.
   -------------------------------------------------------------------------- */

function applyHome() {
  const path = resolve(root, 'index.html');
  let src = readFileSync(path, 'utf8');

  const inline = src.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/);
  if (!inline) throw new Error('index.html: inline JSON-LD graph not found');
  const doc = JSON.parse(inline[1]);
  const kept = doc['@graph'].filter((n) => n['@type'] !== 'FAQPage');
  if (kept.length !== doc['@graph'].length) {
    doc['@graph'] = kept;
    src = src.replace(
      inline[0],
      `<script type="application/ld+json">\n${JSON.stringify(doc, null, 2)}\n    </script>`
    );
  }

  src = applyFaq(src, FAQ.home, { label: 'BUYER FAQ', accent: 'text-pink' });
  src = applyJsonLd(src, [faqPageNode('/', FAQ.home)]);
  writeFileSync(path, src);
  return `index.html (${FAQ.home.length} questions)`;
}

/* --------------------------------------------------------------------------
   Service pages & the portfolio index
   -------------------------------------------------------------------------- */

function applyService(slug) {
  const file = `services/${slug}.html`;
  const path = resolve(root, file);
  const meta = SERVICES[slug];
  const items = FAQ[slug];
  const route = `/services/${slug}.html`;

  let src = readFileSync(path, 'utf8');
  src = applyFaq(src, items, { label: `${meta.label.toUpperCase()} FAQ`, accent: 'text-yellow' });
  src = applyJsonLd(src, [
    organizationNode(),
    serviceNode(route, meta),
    faqPageNode(route, items),
    breadcrumbNode(route, [
      { name: 'Services', url: '/#services' },
      { name: meta.name },
    ]),
  ]);
  writeFileSync(path, src);
  return `${file} (${items.length} questions)`;
}

function applyWork() {
  const path = resolve(root, 'work.html');
  let src = readFileSync(path, 'utf8');
  src = applyJsonLd(src, [
    organizationNode(),
    breadcrumbNode('/work.html', [{ name: 'Work & Case Studies' }]),
    {
      '@type': 'CollectionPage',
      '@id': `${SITE}/work.html#collection`,
      name: 'Digital & Performance Marketing Case Studies in India',
      url: `${SITE}/work.html`,
      inLanguage: 'en-IN',
      isPartOf: { '@id': `${SITE}/#website` },
      about: { '@id': `${SITE}/#organization` },
    },
  ]);
  writeFileSync(path, src);
  return 'work.html (schema only)';
}

